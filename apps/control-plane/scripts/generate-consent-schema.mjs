import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { drizzleAdapter } from "@c15t/backend/db/adapters/drizzle";
import { DB } from "@c15t/backend/db/schema";
import { consentTablePrefix } from "../server/consent.ts";

const outputPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../../packages/core/src/db/consent-schema.ts",
);

// The adapter only needs its provider to render the schema; no connection is opened.
const { code } = DB.names
  .prefix(consentTablePrefix)
  .client(drizzleAdapter({ db: {}, provider: "postgresql" }))
  .generateSchema("latest", "drizzle");

await writeFile(
  outputPath,
  [
    "// Consent storage for the self-hosted c15t backend mounted at /api/c15t.",
    "// Generated by `pnpm consent:generate`; regenerate it when upgrading",
    "// @c15t/backend and add a Drizzle migration for any change.",
    "/* eslint-disable @typescript-eslint/no-unused-vars */",
    "",
    code,
    "",
  ].join("\n"),
);
