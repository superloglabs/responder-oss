import { describe, expect, it } from "vitest";
import { cloudWatchMetricName, humanizeCloudWatchName } from "./cloudwatch-metric-names";

describe("CloudWatch metric names", () => {
  it("names a known metric by its service, title and description", () => {
    expect(cloudWatchMetricName("amazonaws.com/AWS/EC2/CPUUtilization")).toEqual({
      description: "Percent of the instance's allocated CPU in use.",
      group: "AWS EC2",
      metric: "CPUUtilization",
      namespace: "AWS/EC2",
      standalone: "EC2 CPU utilization",
      title: "CPU utilization",
    });
    expect(cloudWatchMetricName("amazonaws.com/ECS/ContainerInsights/MemoryUtilized")).toMatchObject({
      group: "AWS ECS Container Insights",
      standalone: "ECS Container Insights memory used",
      title: "Memory used",
    });
  });

  it("names status-code counts and protocol variants from a pattern", () => {
    expect(cloudWatchMetricName("amazonaws.com/AWS/ApplicationELB/HTTPCode_Target_5XX_Count")).toMatchObject({
      description: "Responses with a 5XX status returned by targets.",
      title: "Target 5XX responses",
    });
    expect(cloudWatchMetricName("amazonaws.com/AWS/ApplicationELB/HTTPCode_ELB_502_Count")).toMatchObject({
      description: "Responses with a 502 status generated by the load balancer.",
      title: "Load balancer 502 responses",
    });
    expect(cloudWatchMetricName("amazonaws.com/AWS/NetworkELB/ActiveFlowCount_TLS")).toMatchObject({
      description: "Concurrent flows from clients to targets, over TLS.",
      title: "Active flows (TLS)",
    });
  });

  it("reads an unknown metric or namespace from its CloudWatch name", () => {
    expect(cloudWatchMetricName("amazonaws.com/ECS/ContainerInsights/ContainerCpuUtilized")).toMatchObject({
      description: "CloudWatch metric ContainerCpuUtilized in ECS/ContainerInsights.",
      title: "Container CPU utilized",
    });
    expect(cloudWatchMetricName("amazonaws.com/AWS/Kinesis/GetRecords.IteratorAgeMilliseconds")).toMatchObject({
      group: "AWS Kinesis",
    });
    expect(cloudWatchMetricName("amazonaws.com/MyApp/Checkout/OrdersPlaced")).toMatchObject({
      group: "AWS MyApp Checkout",
      title: "Orders placed",
    });
  });

  it("leaves other metric names alone", () => {
    expect(cloudWatchMetricName("http.server.request.duration")).toBeNull();
    expect(cloudWatchMetricName("amazonaws.com/CPUUtilization")).toBeNull();
    expect(cloudWatchMetricName("amazonaws.com/AWS/EC2/")).toBeNull();
  });

  it("splits CloudWatch names into words and keeps acronyms", () => {
    expect(humanizeCloudWatchName("CpuUtilized")).toBe("CPU utilized");
    expect(humanizeCloudWatchName("TCP_Target_Reset_Count")).toBe("TCP target reset count");
    expect(humanizeCloudWatchName("ApproximateNumberOfMessagesVisible")).toBe("Approximate number of messages visible");
  });
});
