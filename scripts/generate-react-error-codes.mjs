import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

// Writes React's production error messages by code from React's
// scripts/error-codes/codes.json at one commit. Pass a commit SHA to update the
// table; without one it uses the commit the table was generated from.
const commit = process.argv[2] ?? "76baa3b5434fad315ece9cfd4d20d7a8d6c34a25";
const OUTPUT_PATH = resolve("packages/core/src/telemetry/react-error-codes.ts");
const sourceUrl = `https://raw.githubusercontent.com/facebook/react/${commit}/scripts/error-codes/codes.json`;

const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`${sourceUrl} answered ${response.status}`);
const codes = await response.json();

const lines = [
  "// Production React's error messages by code, from",
  `// https://github.com/facebook/react/blob/${commit.slice(0, 12)}/scripts/error-codes/codes.json`,
  "// (MIT License, Copyright (c) Meta Platforms, Inc. and affiliates).",
  "// Generated by scripts/generate-react-error-codes.mjs; codes are only added,",
  "// never reused, so a newer commit only appends entries.",
  "export const reactErrorMessages: Readonly<Record<string, string>> = {",
  ...Object.keys(codes)
    .sort((a, b) => Number(a) - Number(b))
    .map((code) => `  ${code}: ${JSON.stringify(codes[code])},`),
  "};",
  "",
];
await writeFile(OUTPUT_PATH, lines.join("\n"));
console.log(`Wrote ${Object.keys(codes).length} React error codes to ${OUTPUT_PATH}`);
