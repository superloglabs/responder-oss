import { randomBytes } from "node:crypto";
import {
  chmodSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, resolve } from "node:path";
import process from "node:process";

const environmentFile = resolve(process.argv[2] ?? ".env.local");
const workspacePath = resolve(process.argv[3] ?? process.cwd());
const basePort = Number(process.argv[4]);

if (!Number.isInteger(basePort) || basePort < 1 || basePort > 65_532) {
  throw new Error(`Invalid local base port: ${process.argv[4] ?? "missing"}`);
}

function slug(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
}

function shellValue(value) {
  if (/^[a-zA-Z0-9_./:@%+,=-]*$/.test(value)) return value;
  return `'${value.replaceAll("'", "'\\''")}'`;
}

let original = "";
try {
  original = readFileSync(environmentFile, "utf8");
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

const lines = original ? original.replace(/\n$/, "").split("\n") : [];
const existing = new Map();
for (const line of lines) {
  const match = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
  if (match && !existing.has(match[1])) existing.set(match[1], match[2]);
}

function preserved(key, fallback) {
  const value = existing.get(key);
  return value === undefined ? fallback : value;
}

function requiredSecret(key, encoding = "hex") {
  const value = existing.get(key);
  if (value && value !== "''" && value !== '""') return value;
  return randomBytes(32).toString(encoding);
}

const workspaceSlug = slug(basename(workspacePath)) || "local";
const updates = new Map([
  ["RESPONDER_WORKSPACE_PATH", shellValue(workspacePath)],
  ["RESPONDER_WORKSPACE_SLUG", workspaceSlug],
  ["RESPONDER_PORTLESS_NAME", `responder.${workspaceSlug}`],
  ["RESPONDER_LOCAL_TLD", preserved("RESPONDER_LOCAL_TLD", "local")],
  ["COMPOSE_PROJECT_NAME", `responder-${workspaceSlug}`],
  ["CONTROL_PLANE_WEB_PORT", String(basePort)],
  ["CONTROL_PLANE_API_PORT", String(basePort + 1)],
  ["LOCAL_DATABASE_PORT", String(basePort + 3)],
  [
    "DATABASE_URL",
    `postgresql://responder:responder@127.0.0.1:${basePort + 3}/responder`,
  ],
  ["DATABASE_POOL_SIZE", preserved("DATABASE_POOL_SIZE", "5")],
  ["BETTER_AUTH_URL", `http://127.0.0.1:${basePort}`],
  ["CONTROL_PLANE_URL", `http://127.0.0.1:${basePort}`],
  ["RESPONDER_APP_URL", `http://127.0.0.1:${basePort}`],
  ["BETTER_AUTH_SECRET", requiredSecret("BETTER_AUTH_SECRET")],
  ["INTERNAL_INGEST_TOKEN", requiredSecret("INTERNAL_INGEST_TOKEN")],
  [
    "CREDENTIAL_ENCRYPTION_KEY",
    requiredSecret("CREDENTIAL_ENCRYPTION_KEY", "base64"),
  ],
  ["BILLING_ENABLED", preserved("BILLING_ENABLED", "false")],
  ["AUTUMN_SECRET_KEY", preserved("AUTUMN_SECRET_KEY", "")],
]);

// Variables from the retired local Eve agent. Strip them so regenerating an
// existing worktree's file stops routing investigations at the deleted service;
// the worker now consumes the shared queue instead.
const removed = new Set(["AGENT_PORT", "AGENT_URL"]);

const written = new Set();
const output = [];
if (!original) {
  output.push(
    "# Generated by pnpm local:setup. Do not copy this file between worktrees.",
  );
}

for (const line of lines) {
  const match = line.match(/^([A-Z][A-Z0-9_]*)=/);
  const key = match?.[1];
  if (key && removed.has(key)) continue;
  if (!key || !updates.has(key)) {
    output.push(line);
    continue;
  }
  if (written.has(key)) continue;
  output.push(`${key}=${updates.get(key)}`);
  written.add(key);
}

for (const [key, value] of updates) {
  if (written.has(key)) continue;
  output.push(`${key}=${value}`);
}

const temporaryFile = `${environmentFile}.${process.pid}.tmp`;
try {
  writeFileSync(temporaryFile, `${output.join("\n")}\n`, { mode: 0o600 });
  renameSync(temporaryFile, environmentFile);
  chmodSync(environmentFile, 0o600);
} finally {
  rmSync(temporaryFile, { force: true });
}
